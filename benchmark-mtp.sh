#!/usr/bin/env bash
# Local directional runner for the default Laguna XS 2.1 MTP track.
set -euo pipefail

usage() {
  cat <<'EOF'
Usage: ./benchmark-mtp.sh [--local-iterate|--local-submit]

Runs the trained-assistant MTP path against a locally generated serial oracle
and writes the Yukon score payload to MLXFAST_SCORE_PATH (default: score.json).

The local oracle is generated by the current candidate and therefore checks MTP
parity and speed direction, not official target fidelity. The ranked workflow
uses organizer-pinned hidden goldens and is the correctness authority.
EOF
}

mode="${1:---local-iterate}"
case "${mode}" in
  --local-iterate)
    token_count="${MLXFAST_MTP_LOCAL_ITERATE_TOKENS:-64}"
    ;;
  --local-submit)
    token_count="${MLXFAST_MTP_LOCAL_SUBMIT_TOKENS:-128}"
    ;;
  -h|--help)
    usage
    exit 0
    ;;
  *)
    usage >&2
    exit 2
    ;;
esac

if ! [[ "${token_count}" =~ ^[1-9][0-9]*$ ]] || (( token_count > 512 )); then
  echo "benchmark-mtp: token count must be an integer in 1...512" >&2
  exit 2
fi

repo_root="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
cd "${repo_root}"

swift_bin="${MLXFAST_SWIFT_BIN:-.build/release/mlxfast-swift}"
contract_path="${MLXFAST_MTP_CONTRACT_PATH:-fixtures/laguna_xs_2_1_mtp_track.json}"
prompt_path="${MLXFAST_MTP_LOCAL_PROMPT_PATH:-correctness_prompts/public_longcopy_gate_english.txt}"
score_path="${MLXFAST_SCORE_PATH:-score.json}"
work_root="${MLXFAST_MTP_LOCAL_WORK_DIR:-.mlxfast-local-mtp}"
block_size="${MLXFAST_MTP_BLOCK_SIZE:-4}"

if ! [[ "${block_size}" =~ ^[2-4]$ ]]; then
  echo "benchmark-mtp: block size must be in 2...4" >&2
  exit 2
fi
if [[ ! -x "${swift_bin}" ]]; then
  echo "benchmark-mtp: missing ${swift_bin}; run ./setup.sh first" >&2
  exit 1
fi
if [[ ! -s "${contract_path}" || ! -s "${prompt_path}" ]]; then
  echo "benchmark-mtp: missing MTP contract or local prompt" >&2
  exit 1
fi

eval "$(./setup-mtp.sh --print-paths)"
: "${MLXFAST_MTP_TARGET_DIR:?setup-mtp.sh did not provide the target path}"
: "${MLXFAST_MTP_ASSISTANT_DIR:?setup-mtp.sh did not provide the assistant path}"
if [[ ! -s "${MLXFAST_MTP_TARGET_DIR}/config.json" || ! -s "${MLXFAST_MTP_ASSISTANT_DIR}/config.json" ]]; then
  echo "benchmark-mtp: MTP target or assistant is missing; run ./setup-mtp.sh" >&2
  exit 1
fi

mkdir -p "${work_root}" "$(dirname "${score_path}")"
run_dir="$(mktemp -d "${work_root%/}/run.XXXXXX")"
cleanup() {
  if [[ -n "${score_tmp:-}" ]]; then
    rm -f -- "${score_tmp}"
  fi
  rm -rf -- "${run_dir}"
}
trap cleanup EXIT

weights_path="${run_dir}/weights"
golden_path="${run_dir}/golden.json"
serial_report="${run_dir}/serial.json"
mtp_report="${run_dir}/mtp.json"
score_tmp="${score_path}.tmp"

echo "benchmark-mtp: transforming the pinned Laguna target" >&2
"${swift_bin}" transform \
  --reference "${MLXFAST_MTP_TARGET_DIR}" \
  --output "${weights_path}"

echo "benchmark-mtp: generating a candidate-local serial oracle (${token_count} tokens)" >&2
"${swift_bin}" generate-golden \
  --prompt-file "${prompt_path}" \
  --weights "${weights_path}" \
  --tokenizer "${MLXFAST_MTP_TARGET_DIR}" \
  --output "${golden_path}" \
  --name "laguna-xs-2.1-mtp-local" \
  --steps "$((token_count + 1))"

echo "benchmark-mtp: measuring serial K=1 control" >&2
"${swift_bin}" mtp-probe \
  --weights "${weights_path}" \
  --golden "${golden_path}" \
  --block-size "${block_size}" \
  --tokens "${token_count}" > "${serial_report}"

echo "benchmark-mtp: measuring trained-assistant exact-pair decode" >&2
"${swift_bin}" mtp-benchmark \
  --target-source "${MLXFAST_MTP_TARGET_DIR}" \
  --weights "${weights_path}" \
  --assistant "${MLXFAST_MTP_ASSISTANT_DIR}" \
  --contract "${contract_path}" \
  --golden "${golden_path}" \
  --block-size "${block_size}" \
  --tokens "${token_count}" \
  --target-verification exact-pair \
  --require-trained-assistant > "${mtp_report}"

jq -e '
  .all_tokens_matched == true
  and .official_score_produced == false
  and (.parent_measured_seconds_per_token | type == "number" and . > 0)
' "${serial_report}" >/dev/null
jq -e --arg track "laguna-xs-2.1-mtp-v1" '
  .track_id == $track
  and .uses_trained_drafter == true
  and .all_tokens_matched == true
  and .official_score_produced == false
  and (.parent_measured_seconds_per_token | type == "number" and . > 0)
' "${mtp_report}" >/dev/null

serial_spt="$(jq -r '.parent_measured_seconds_per_token' "${serial_report}")"
mtp_spt="$(jq -r '.parent_measured_seconds_per_token' "${mtp_report}")"
score="$(jq -n --argjson serial "${serial_spt}" --argjson mtp "${mtp_spt}" '$serial / $mtp')"
jq -e 'type == "number" and . > 0' <<<"${score}" >/dev/null

jq -n \
  --arg track "laguna-xs-2.1-mtp-v1" \
  --arg mode "${mode#--}" \
  --argjson score "${score}" \
  --argjson token_count "${token_count}" \
  --argjson block_size "${block_size}" \
  --argjson serial_spt "${serial_spt}" \
  --argjson mtp_spt "${mtp_spt}" \
  --argjson accepted_rate "$(jq -r '.accepted_draft_rate' "${mtp_report}")" \
  '{
    score: $score,
    passed: true,
    track_id: $track,
    metrics: {
      mode: ("mtp-" + $mode),
      oracle: "candidate-local-serial-control",
      official_score: false,
      decode_tokens: $token_count,
      block_size: $block_size,
      all_tokens_matched: true,
      uses_trained_drafter: true,
      serial_seconds_per_token: $serial_spt,
      mtp_seconds_per_token: $mtp_spt,
      mtp_decode_speedup: $score,
      accepted_draft_rate: $accepted_rate
    }
  }' > "${score_tmp}"
mv "${score_tmp}" "${score_path}"
cat "${score_path}"
